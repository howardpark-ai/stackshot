"""Write StampTable.tla: what the real save-time stamp does, for every case the model uses.

Usage: extract_stamp.py <out-dir>      (run from the stackshot checkout under test, through uv; see SKILL.md)

The spec in spec/ItemPhase.tla never says what a save stores. This script asks the code. For each
(status, stored phase, stored waits_on, shown reading) it builds an item, runs the real
`stackshot.service.stamp._phase_stamp` on it, reads back `metadata.phase` and `metadata.waits_on`,
and writes the answers as a TLA+ function. The one thing replaced is `_stamp_values`'s read of the
item's fields (the derivation of the shown model, which needs a store and a config): its answer is
a Model built here, passed through the real `model.stamp_values`. So the closed-item pop in
`_phase_stamp`, `model.stamp_values` and `model.shown_pair` all run as they are.
"""
import itertools
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from stackshot.model import model as M  # noqa: E402
from stackshot.service import stamp  # noqa: E402

STATUS = ("open", "closed")
# the pairs an item can store, as the stamp itself writes them (one kind of wait of each family is enough: time ends by the clock, relay by the owner's news)
PAIRS = (("", ""), ("alive", ""), ("waiting", "time"), ("waiting", "relay"))
SHOWN = {
    "alive": M.Model(M.ALIVE, "doing"),
    "wtime": M.Model(M.WAITING, "doing", wait=M.Wait(kind="time", kind_explicit=True)),
    "wrelay": M.Model(M.WAITING, "doing", wait=M.Wait(kind="relay", kind_explicit=True)),
}


def run(status: str, pair: tuple[str, str], shown: str) -> tuple[str, str]:
    meta = {k: v for k, v in zip(("phase", "waits_on"), pair) if v}
    item = {"status": status, "metadata": meta}
    stamp._stamp_values = lambda gid, it: M.stamp_values(it, SHOWN[shown])  # the one stand-in: see the module docstring
    stamp._phase_stamp("x", item)
    return item["metadata"].get("phase", ""), item["metadata"].get("waits_on", "")


def main(out: pathlib.Path) -> None:
    rows = []
    for status, pair, shown in itertools.product(STATUS, PAIRS, SHOWN):
        got = run(status, pair, shown)
        key = f'<<"{status}", "{pair[0]}", "{pair[1]}", "{shown}">>'
        rows.append(f'  ({key} :> <<"{got[0]}", "{got[1]}">>)')
    text = ("---- MODULE StampTable ----\n"
            "\\* Generated by extract_stamp.py from stackshot/service/stamp.py _phase_stamp. Do not edit.\n"
            "EXTENDS TLC\n"
            "\\* Stamp[<<status, stored phase, stored waits_on, shown reading>>] = <<phase, waits_on>> after a save\n"
            "Stamp == \n" + " @@\n".join(rows) + "\n====\n")
    (out / "StampTable.tla").write_text(text, encoding="utf-8")
    print(f"extracted {len(rows)} save outcomes from stamp._phase_stamp")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]))
